const cam = window.__porco.camera;
const v = cam.matrixWorldInverse.elements, m = cam.projectionMatrix.elements;
const project = (px, py, pz) => {
  const ex = v[0]*px+v[4]*py+v[8]*pz+v[12];
  const ey = v[1]*px+v[5]*py+v[9]*pz+v[13];
  const ez = v[2]*px+v[6]*py+v[10]*pz+v[14];
  const cx = m[0]*ex+m[4]*ey+m[8]*ez+m[12];
  const cy = m[1]*ex+m[5]*ey+m[9]*ez+m[13];
  const cw = m[3]*ex+m[7]*ey+m[11]*ez+m[15];
  return [(cx/cw*0.5+0.5)*window.innerWidth, (-(cy/cw)*0.5+0.5)*window.innerHeight];
};
const invV = cam.matrixWorld.elements;
const camPos = [invV[12], invV[13], invV[14]];
const fwd = [-invV[8], -invV[9], -invV[10]];
const t = Math.abs(fwd[1]) > 1e-5 ? -camPos[1] / fwd[1] : 300;
const tt = Math.min(Math.max(t, 20), 400);
const hit = [camPos[0] + fwd[0]*tt, 0, camPos[2] + fwd[2]*tt];
const a = project(hit[0], 0, hit[2]);
const b = project(hit[0] + 0.8211*150, 0, hit[2] - 0.5733*150);
const L = Math.hypot(b[0]-a[0], b[1]-a[1]) || 1;
return { dx: (b[0]-a[0])/L, dy: (b[1]-a[1])/L, hit, camPos, elapsed: window.__porco.qa.elapsed };
